"""Generate docs/sensitivity.md: which parameters drive the decision for each bundled profile."""

from pathlib import Path

from dhill.profiles.loader import load_builtin
from dhill.sensitivity import tornado
from dhill.weather import synthetic_weather

W = synthetic_weather("abu_dhabi", "summer_clear", days=2)
CASES = [
    ("ugv_medium_inspection", "drive", "2026-08-05T05:00"),
    ("sidewalk_delivery_robot", "drive", "2026-08-05T08:00"),
    ("pv_cleaning_robot", "work", "2026-08-05T05:00"),
    ("clearpath_jackal", "drive", "2026-08-05T05:00"),
]

out = [
    "# Sensitivity: what to measure first",
    "",
    "Generated by `scripts/gen_sensitivity_doc.py` (synthetic Abu Dhabi summer day, 1 h full-scale mission, illustrative L0 profiles).",
    "Each parameter is moved by one prior standard deviation (from its provenance) while the rest stay nominal; the table shows the",
    "swing in peak temperature of the component that binds at the nominal point. Shares assume additive, independent effects.",
    "**These rankings belong to the illustrative profiles. A real robot will rank differently; re-run `dhill sensitivity` on its profile.**",
    "",
]
for pid, mode, start in CASES:
    rep = tornado(load_builtin(pid), W, start, 1.0, mode)
    out += [
        f"## {pid} at {start} UTC",
        "",
        f"Binding component: **{rep.binding_component}**, nominal peak {rep.nominal_peak_c:.1f} C against an allowed {rep.allowed_c:.0f} C; prior spread about +/-{rep.total_sd_k:.1f} K.",
        "",
        "| Rank | Parameter | Source | Prior sigma | Swing (K) | Share | Gain if measured (K) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rep.rows[:8]:
        out.append(
            f"| {r.rank} | `{r.key}` | {r.source} | {r.sigma:.2f} | {r.swing_k:.2f} | {r.share:.0%} | {r.measured_gain_k:.2f} |"
        )
    top3 = sum(r.share for r in rep.rows[:3])
    out += ["", f"The top three parameters carry {top3:.0%} of the additive variance.", ""]
Path(__file__).resolve().parents[1].joinpath("docs/sensitivity.md").write_text(
    "\n".join(out), encoding="utf-8"
)
print("wrote docs/sensitivity.md")
