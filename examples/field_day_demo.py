"""Dry run of the field day pipeline on SYNTHETIC telemetry (no robot, no field data).

Steps, as they would run with the AAU logging session (docs/field-test-kit.md):
1. Day 1 (calibration): telemetry from a hidden robot; fit the profile with `calibrate`.
2. Day 2 (validation, held out): telemetry from the same hidden robot on another day; check both the L0
   profile and the calibrated profile with `validate` against the criteria of docs/validation-protocol.md.

The hidden robot, its telemetry and the weather are SYNTHETIC and share the model's structure (inverse
crime), so a PASS here shows only that the pipeline works, not that the model is right.
Run: python examples/field_day_demo.py   Output: examples/field_day_demo_output.md
"""

from __future__ import annotations

from pathlib import Path

from dhill.calibrate import calibrate, synthetic_telemetry
from dhill.profiles.loader import load_builtin
from dhill.validate import render_markdown, validate
from dhill.weather import synthetic_weather

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "examples" / "field_day_demo_output.md"
LABEL = "SYNTHETIC telemetry and weather; hidden robot shares the model structure (dry run, not field data)"


def main() -> str:
    base = load_builtin("clearpath_jackal")
    hidden = base.with_overrides(
        {
            "surface.alpha_clean": base.value("surface.alpha_clean") * 1.3,
            "coupling.ua_shell_interior_w_k": base.value("coupling.ua_shell_interior_w_k") * 0.6,
        }
    )
    w = synthetic_weather("al_ain", "summer_clear", days=3)
    day1 = synthetic_telemetry(hidden, w, "2026-08-05T02:00", hours=12, seed=11)
    day2 = synthetic_telemetry(hidden, w, "2026-08-06T02:00", hours=12, seed=12)
    cal, fit = calibrate(base, w, day1)
    parts = [
        "# Field day dry run (SYNTHETIC)",
        "",
        f"**{LABEL}.** Generated by `examples/field_day_demo.py`.",
        "",
        "Hidden robot: `clearpath_jackal` with absorptance x1.3 and shell to interior conductance x0.6.",
        f"Calibration on day 1: hold out error {fit.rmse_holdout_k:.2f} K after fitting, "
        f"{fit.rmse_prior_holdout_k:.2f} K with the prior. The code labels a calibrated profile "
        f"{cal.evidence_level}; on synthetic telemetry that label carries no evidence and every shipped "
        "profile stays L0.",
        "",
    ]
    for name, prof in (("L0 profile", base), ("calibrated profile", cal)):
        rep = validate(prof, w, day2, note=f"{LABEL}. Day 2 held out; {name}.")
        md = render_markdown(rep, "synthetic day 2").replace(
            "# Validation report", "## Validation", 1
        )
        parts += [md, ""]
    text = "\n".join(parts)
    OUT.write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(main())
